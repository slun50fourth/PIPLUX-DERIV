export const MarketIcon = ({ type, size }: { type: string; size?: IconSize }) => {
    const key = typeof type === 'string' ? type.toUpperCase() : '';
    const iconName = MARKET_ICON_NAMES[key];
    const Icon = (iconName && MarketIcons[iconName]) || IllustrativeMarketsIcon;
    if (!Icon) return null;
    return <Icon iconSize={size ?? 'xs'} />;
};
